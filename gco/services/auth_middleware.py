"""
Authentication middleware for validating requests from API Gateway.

Except for explicit health and metrics probes, every request must carry the
short-lived HMAC envelope generated by a trusted API Gateway proxy Lambda. The
envelope binds the signature version, timestamp, random nonce, HTTP method,
exact path and query string, and SHA-256 body digest. The middleware validates
freshness and integrity and rejects process-local nonce replays.

Security Flow:
    1. API Gateway validates client IAM credentials (SigV4)
    2. Lambda signs the exact backend request with the shared signing key
    3. This middleware validates the HMAC envelope and consumes its nonce
    4. Invalid, stale, tampered, or replayed envelopes result in 403 Forbidden

Secret Rotation Support:
    During rotation, signatures are validated against both AWSCURRENT and
    AWSPENDING signing keys for zero-downtime rotation. Successful refreshes
    are cached with a bounded stale grace period; expired caches fail closed.

Environment Variables:
    AUTH_SECRET_ARN: ARN of the Secrets Manager secret containing the signing key
    GCO_DEV_MODE: Set to "true" to allow unauthenticated requests when no
        secret is configured. Without this flag, missing AUTH_SECRET_ARN
        causes 503 errors (fail-closed). This prevents accidental
        unauthenticated deployments due to misconfiguration.
"""

